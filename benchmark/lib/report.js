/**
 * @file report.js
 * @description Renders `benchmark/results/baseline.json` into a human-readable Markdown baseline.
 *              The generated section of BASELINE.md is rewritten on every run; the hand-written
 *              interpretation below the marker is preserved.
 */
"use strict";

const fs = require("fs");

const GENERATED_START = "<!-- BENCHMARK-GENERATED:START -->";
const GENERATED_END = "<!-- BENCHMARK-GENERATED:END -->";

function ms(v, d = 2) {
    return Number.isFinite(v) ? v.toFixed(d) : "n/a";
}

function kb(bytes) {
    return Number.isFinite(bytes) ? (bytes / 1024).toFixed(1) : "n/a";
}

function table(headers, rows) {
    const head = `| ${headers.join(" | ")} |`;
    const sep = `| ${headers.map(() => "---").join(" | ")} |`;
    return [head, sep, ...rows.map((r) => `| ${r.join(" | ")} |`)].join("\n");
}

function summaryCells(s, d = 2) {
    if (!s) return ["n/a", "n/a", "n/a", "n/a", "0", "n/a"];
    return [ms(s.median, d), ms(s.iqr, d), ms(s.min, d), ms(s.max, d), String(s.n), s.stability];
}

function section(title, body) {
    return `\n## ${title}\n\n${body}\n`;
}

function curveLine(name, c) {
    if (!c) return `- \`${name}\`: not enough points to fit.`;
    return (
        `- \`${name}\`: **${c.verdict}** — per-unit cost ${c.perUnitFirst.toFixed(4)} ms at the smallest size vs ` +
        `${c.perUnitLast.toFixed(4)} ms at the largest (x${c.perUnitGrowth.toFixed(2)}); ` +
        `linear fit R²=${c.linear.r2.toFixed(4)}, quadratic fit R²=${c.quadratic.r2.toFixed(4)}.`
    );
}

function writeReport(payload, outPath) {
    const { environment: env, records, curves } = payload;
    const parts = [];

    parts.push(GENERATED_START);
    parts.push(
        "\n> This section is regenerated by `node benchmark/run-benchmarks.js`. Do not hand-edit it;\n" +
            "> anything written below the END marker is preserved across runs.\n"
    );

    // ------------------------------------------------------------- environment
    parts.push(
        section(
            "Environment",
            table(
                ["Item", "Value"],
                [
                    ["Run at", env.timestamp],
                    ["CPU", `${env.cpuModel} (${env.cpuCount} logical)`],
                    ["Memory", `${env.totalMemGB} GB`],
                    ["OS", env.platform],
                    ["Node", `${env.node} (V8 ${env.v8})`],
                    ["Chromium", env.chromium || "n/a"],
                    ["Puppeteer", env.puppeteer],
                    ["Repeats per point", String(env.repeats)],
                    ["Quick mode", String(env.quick)],
                    ["Deep sweep", String(Boolean(env.deep))],
                    ["Build measured", env.distSource ? `${env.distSource} (${env.distPath})` : "unrecorded"],
                    ["Build produced at", env.distBuiltAt || "unrecorded"],
                    [
                        "Source revision",
                        env.gitCommit
                            ? `${env.gitCommit.slice(0, 12)}${env.gitDirty ? " (working tree dirty)" : ""}`
                            : "unrecorded"
                    ],
                    ["Groups", env.groups.join(", ")],
                    ["Page errors captured", String((env.pageErrors || []).length)]
                ]
            ) +
                "\n\nAll timings are `performance.now()` deltas taken inside headless Chromium with the GPU " +
                "disabled. Each point is one discarded warm-up pass followed by the stated number of measured " +
                "repeats; the figures are **median** and **inter-quartile range**, never a mean. `stability` is " +
                "derived from IQR as a share of the median: `stable` <= 10%, `usable` <= 25%, `noisy` above that, " +
                "and `below-timer-resolution` for anything under 0.5 ms, where the clock itself is the dominant " +
                "error term."
        )
    );

    // ------------------------------------------------------------- per group
    const byScenario = (scenario) => records.filter((r) => r.scenario === scenario);

    const renderRows = (recs, metrics, extra) =>
        recs.map((r) => {
            const base = [r.label];
            for (const m of metrics) {
                const s = r.summary[m];
                base.push(s ? `${ms(s.median)} ± ${ms(s.iqr)}` : "n/a");
            }
            const last = r.summary[metrics[0]];
            base.push(last ? last.stability : "n/a");
            if (extra) base.push(...extra(r));
            return base;
        });

    // 1. render
    const explicit = byScenario("render.explicit");
    const inferred = byScenario("render.inferred");
    const normalize = byScenario("normalize.only");
    if (explicit.length || inferred.length) {
        let body = "### Explicit JSON Schema\n\n";
        body += table(
            ["Case", "total (ms)", "generate (ms)", "applyChanges (ms)", "stability", "plugins", "controls", "DOM nodes"],
            renderRows(explicit, ["tTotal", "tGenerate", "tApply"], (r) => [
                String(r.meta.plugins),
                String(r.meta.controls),
                String(r.meta.domNodes)
            ])
        );
        body += "\n\n### Inferred from raw data (production hot path)\n\n";
        body += table(
            ["Case", "total (ms)", "generate (ms)", "applyChanges (ms)", "stability", "plugins", "controls", "DOM nodes"],
            renderRows(inferred, ["tTotal", "tGenerate", "tApply"], (r) => [
                String(r.meta.plugins),
                String(r.meta.controls),
                String(r.meta.domNodes)
            ])
        );
        body += "\n\n### Schema normalisation in isolation (no controls, no DOM)\n\n";
        body += table(
            ["Case", "normalize (ms)", "stability"],
            normalize.map((r) => [
                r.label,
                `${ms(r.summary.tNormalize.median)} ± ${ms(r.summary.tNormalize.iqr)}`,
                r.summary.tNormalize.stability
            ])
        );
        body += "\n\n**Curve shape**\n\n";
        body += [
            curveLine("render.explicit total", curves["render.explicit.tTotal"]),
            curveLine("render.inferred total", curves["render.inferred.tTotal"]),
            curveLine("schema normalisation", curves["normalize.only"])
        ].join("\n");
        parts.push(section("1. Render time vs field count", body));
    }

    // 2. inference
    const pureAll = byScenario("infer.pure");
    const e2e = byScenario("infer.e2e");
    if (pureAll.length) {
        const group = (re) => pureAll.filter((r) => re.test(r.label));
        let body = "";
        const blocks = [
            ["Width sweep (flat object)", /pure flat/],
            ["Depth sweep (20 fields per level)", /pure depth/],
            ["Array-of-objects row sweep (15 columns)", /rows x 15 cols/],
            ["Nested arrays-of-objects (fan-out 3)", /nested-array depth/]
        ];
        for (const [title, re] of blocks) {
            const recs = group(re);
            if (!recs.length) continue;
            body += `### ${title}\n\n`;
            body += table(
                ["Case", "infer (ms)", "IQR", "min", "max", "n", "stability", "payload bytes"],
                recs.map((r) => [r.label, ...summaryCells(r.summary.tInfer), String(r.meta.payloadBytes)])
            );
            body += "\n\n";
        }
        if (e2e.length) {
            body += "### End to end: raw data in, rendered control tree out\n\n";
            body += table(
                ["Case", "total (ms)", "generate (ms)", "applyChanges (ms)", "stability", "payload bytes", "plugins", "DOM nodes"],
                renderRows(e2e, ["tTotal", "tGenerate", "tApply"], (r) => [
                    String(r.meta.payloadBytes),
                    String(r.meta.plugins),
                    String(r.meta.domNodes)
                ])
            );
            body += "\n\n";
        }
        body += "**Curve shape**\n\n";
        body += [
            curveLine("inference vs field count", curves["infer.pure.width"]),
            curveLine("inference vs row count", curves["infer.pure.rows"]),
            curveLine("inference vs nesting depth", curves["infer.pure.depth"])
        ].join("\n");
        parts.push(section("2. Inference time vs payload size and nesting depth", body));
    }

    // 3. tables
    const tRender = byScenario("table.render");
    const tAdd = byScenario("table.addRow");
    const tTrunc = byScenario("table.rowTruncation")[0];
    if (tRender.length) {
        let body = "";
        if (tTrunc) {
            body += "### Rendered rows vs model rows\n\n";
            body +=
                "Read the timings below against this table first. `SandboxJSONModel` sizes its list binding " +
                "to the data, and the generated table pages at `growingThreshold` with an explicit \"More\" " +
                "trigger. So one page is painted while the binding holds the whole collection, and the render " +
                "cost below tracks *drawn* rows, not model rows - 200 and 1000 rows cost about the same.\n\n" +
                "`truncated` means rows the binding cannot reach: present in the payload, submitted, and " +
                "impossible to display. A short painted page with a full binding is paging, not truncation. " +
                "Before this was fixed the binding itself stopped at 100 and the extra rows were unreachable.\n\n";
            body += table(
                ["model rows", "painted", "binding length", "model size limit", "DOM rows", "paging", "counter", "unreachable"],
                tTrunc.meta.probes.map((p) => [
                    String(p.modelRows),
                    String(p.renderedItems),
                    String(p.bindingLength),
                    String(p.modelSizeLimit),
                    String(p.domRows),
                    p.growing === null || p.growing === undefined ? "?" : p.growing ? `yes (${p.growingThreshold})` : "no",
                    p.growingReports || "-",
                    p.truncated ? "**yes**" : "no"
                ])
            );
            body += "\n\n";
        }
        body += "### Full table render\n\n";
        body += table(
            ["Case", "total (ms)", "generate (ms)", "applyChanges (ms)", "stability", "controls", "DOM nodes"],
            renderRows(tRender, ["tTotal", "tGenerate", "tApply"], (r) => [
                String(r.meta.controls),
                String(r.meta.domNodes)
            ])
        );
        body += "\n\n### Row-clone path (`Add Row` press, per added row)\n\n";
        body += table(
            ["Case", "add row (ms)", "IQR", "min", "max", "n", "stability"],
            tAdd.map((r) => [r.label, ...summaryCells(r.summary.tAddRow)])
        );

        const tAddPol = byScenario("table.addRowWithPolicies");
        if (tAddPol.length) {
            body += "\n\n### `Add Row` split into handler and re-render, with and without `$row` policies\n\n";
            body +=
                "`press` is the synchronous `TableRowHelper.addRow` path, which includes " +
                "`Engine.onArrayMutated()` and therefore `resetAndEvaluatePoliciesNow()`. " +
                "`applyChanges` is UI5 re-rendering the list afterwards.\n\n";
            body += table(
                ["Case", "total (ms)", "press (ms)", "applyChanges (ms)", "stability"],
                tAddPol.map((r) => [
                    r.label,
                    `${ms(r.summary.tAddTotal.median)} ± ${ms(r.summary.tAddTotal.iqr)}`,
                    `${ms(r.summary.tAddPress.median)} ± ${ms(r.summary.tAddPress.iqr)}`,
                    `${ms(r.summary.tAddApply.median)} ± ${ms(r.summary.tAddApply.iqr)}`,
                    r.summary.tAddTotal.stability
                ])
            );
        }

        body += "\n\n**Curve shape**\n\n";
        body += [3, 8, 15]
            .map((c) => curveLine(`table render, ${c} columns, vs rows`, curves[`table.render.${c}cols`]))
            .concat([
                curveLine("add row (8 columns, no policies) vs existing rows", curves["table.addRow.8cols"]),
                curveLine("add row, 0 $row policies, vs existing rows", curves["table.addRow.0policies"]),
                curveLine("add row, 10 $row policies, vs existing rows", curves["table.addRow.10policies"])
            ])
            .join("\n");
        parts.push(section("3. Table rendering (rows x columns)", body));
    }

    // 4. policy
    const polEngine = byScenario("policy.engineOnly");
    const polChange = byScenario("policy.change");
    const polRow = byScenario("policy.rowExpansion");
    if (polEngine.length || polChange.length) {
        let body = "### `PolicyEngine.evaluate()` in isolation\n\n";
        body += table(
            ["Case", "steady pass (ms)", "IQR", "min", "max", "n", "stability", "first pass (ms)", "expanded rules"],
            polEngine.map((r) => [
                r.label,
                ...summaryCells(r.summary.tSteady),
                ms(r.summary.tFirstPass.median),
                String(r.meta.expandedRules || r.meta.policies)
            ])
        );
        if (polChange.length) {
            body += "\n\n### Committed field change on a policy-carrying form\n\n";
            body += "`commit` is the synchronous change path (parse, validate, ledger, host sync). ";
            body += "`policy flush` is the debounced policy pass, measured separately because `PolicyDelegate` ";
            body += "delays it 200 ms and coalesces a burst of typing into one evaluation. ";
            body +=
                "The headline figures are block-timed (a run of changes measured as one window and divided), " +
                "which beats Chromium's 100 µs clock quantisation; the per-event medians are shown beside them.\n\n";
            body += table(
                [
                    "Case",
                    "commit (ms, block)",
                    "policy flush (ms, block)",
                    "commit (ms, per event)",
                    "flush (ms, per event)",
                    "block stability"
                ],
                polChange.map((r) => [
                    r.label,
                    `${ms(r.summary.tCommitBlock.median, 3)} ± ${ms(r.summary.tCommitBlock.iqr, 3)}`,
                    `${ms(r.summary.tPolicyEvalBlock.median, 3)} ± ${ms(r.summary.tPolicyEvalBlock.iqr, 3)}`,
                    ms(r.summary.tCommit.median, 3),
                    ms(r.summary.tPolicyEval.median, 3),
                    r.summary.tCommitBlock.stability
                ])
            );
        }
        const polLookup = byScenario("policy.registryLookup")[0];
        if (polLookup) {
            body += "\n\n### Registry round trip, performed once per rule per pass\n\n";
            body +=
                "`PolicyEngine` resolves its effect and condition plugins through `PluginRegistry`, which does a " +
                "synchronous `sap.ui.require()` plus a `new Ctor()` on every call. These are per-call costs; " +
                "multiply by (rules x targets) to get the share of one evaluation pass spent here.\n\n";
            body += table(
                ["Call", "per call (µs)", "IQR", "min", "max", "n", "stability"],
                Object.entries(polLookup.summary).map(([k, s]) => [k, ...summaryCells(s, 3)])
            );
        }
        if (polRow.length) {
            body += "\n\n### `$row` expansion inside a rendered table (full host)\n\n";
            body += table(
                ["Case", "policy flush (ms)", "IQR", "min", "max", "n", "stability", "expanded rules"],
                polRow.map((r) => [
                    r.label,
                    ...summaryCells(r.summary.tPolicyEval),
                    String(r.meta.expandedRules)
                ])
            );
        }
        const polStorm = byScenario("policy.deltaStorm");
        if (polStorm.length) {
            body += "\n\n### Delta storm: `resetAndEvaluatePoliciesNow()` on a `$row` table\n\n";
            body +=
                "Steady-state evaluation emits no deltas, because `PolicyEngine` suppresses states that " +
                "have not changed. Resetting the differential matrix makes every rule emit one, and a delta " +
                "targeting a cloned row cell has no registered plugin, so it is applied by walking the whole " +
                "generated control tree. `Engine.onArrayMutated()` calls this on every table row add and " +
                "delete, so this is the cost of one row insertion, not a synthetic case.\n\n";
            body += table(
                [
                    "Case",
                    "reset+evaluate (ms)",
                    "IQR",
                    "steady evaluate (ms)",
                    "ratio",
                    "expanded rules",
                    "controls in tree",
                    "stability"
                ],
                polStorm.map((r) => [
                    r.label,
                    ms(r.summary.tResetAndEvaluate.median),
                    ms(r.summary.tResetAndEvaluate.iqr),
                    ms(r.summary.tSteadyEvaluate.median),
                    (r.summary.tResetAndEvaluate.median / Math.max(r.summary.tSteadyEvaluate.median, 1e-6)).toFixed(1) +
                        "x",
                    String(r.meta.expandedRules),
                    String(r.meta.controls),
                    r.summary.tResetAndEvaluate.stability
                ])
            );
        }

        body +=
            "\n\n**Curve shape**\n\n" +
            [
                curveLine("policy evaluate vs policy count (flat)", curves["policy.engineOnly.flat"]),
                curveLine("delta storm vs table rows (5 policies)", curves["policy.deltaStorm.rows"])
            ].join("\n");
        parts.push(section("4. Policy engine cost per field change", body));
    }

    // 5. validation
    const vPipe = byScenario("validate.pipelineOnly");
    const vChange = byScenario("validate.change").concat(byScenario("validate.change.invalid"));
    if (vPipe.length || vChange.length) {
        let body = "### Raw validator chain (`PipelineManager.runValidators`)\n\n";
        body += table(
            ["Case", "per call (µs)", "IQR", "min", "max", "n", "stability"],
            vPipe.map((r) => [r.label, ...summaryCells(r.summary.tPerCallMicros, 3)])
        );
        body += "\n\n### Committed change on a validator-heavy form\n\n";
        body +=
            "`commit` is block-timed (a run of committed changes measured as one window and divided). " +
            "`validateAll` is the submit-time whole-form pass.\n\n";
        body += table(
            [
                "Case",
                "commit (ms)",
                "commit IQR",
                "commit stability",
                "validateAll (ms)",
                "validateAll IQR",
                "validateAll stability"
            ],
            vChange.map((r) => [
                r.label,
                ms(r.summary.tCommitBlock.median, 3),
                ms(r.summary.tCommitBlock.iqr, 3),
                r.summary.tCommitBlock.stability,
                ms(r.summary.tValidateAll.median),
                ms(r.summary.tValidateAll.iqr),
                r.summary.tValidateAll.stability
            ])
        );
        body += "\n\n**Curve shape**\n\n";
        body += [
            curveLine("per-change cost vs field count (clean form)", curves["validate.change.fields"]),
            curveLine("validateAll vs field count (clean form)", curves["validate.validateAll.fields"]),
            curveLine("per-change cost vs field count (ledger full)", curves["validate.change.invalidLedger"]),
            curveLine("validateAll vs field count (ledger full)", curves["validate.validateAll.invalidLedger"])
        ].join("\n");
        parts.push(section("5. Validation pipeline cost per change", body));
    }

    // 6. memory
    const mem = records.filter((r) => r.group === "memory");
    if (mem.length) {
        let body =
            "Heap is read through CDP: three `HeapProfiler.collectGarbage` passes, then `Runtime.getHeapUsage`. " +
            "`Nodes` and `JSEventListeners` come from `Performance.getMetrics`; `controls` is " +
            "`sap.ui.core.Element.registry.size`, which counts every UI5 control still registered — the most " +
            "direct evidence of a lifecycle leak, since a destroyed control deregisters itself. Each scenario " +
            "is run over several identical passes: a delta that appears only in pass 1 is warm-up, a delta " +
            "that repeats at the same rate in later passes is a leak, and a delta that changes sign is " +
            "allocator noise.\n\n";
        body += table(
            [
                "Scenario",
                "pass",
                "heap Δ (KB)",
                "heap Δ/cycle (KB)",
                "controls Δ",
                "DOM nodes Δ",
                "listeners Δ",
                "live controls after",
                "live DOM after",
                "wall (ms)"
            ],
            mem.map((r) => [
                r.label.replace(/ \[pass \d+\]$/, ""),
                String(r.pass != null ? r.pass : "-"),
                kb(r.meta.deltaHeapBytes),
                (r.meta.deltaHeapPerCycleBytes / 1024).toFixed(2),
                String(r.meta.deltaUiControls),
                String(r.meta.deltaDomNodes),
                String(r.meta.deltaListeners),
                String(r.meta.absUiControlsAfter != null ? r.meta.absUiControlsAfter : "-"),
                String(r.meta.absDomNodesAfter != null ? r.meta.absDomNodesAfter : "-"),
                r.meta.wallMs != null ? String(r.meta.wallMs) : "-"
            ])
        );
        const errs = mem.filter((r) => r.meta.error);
        if (errs.length) {
            body += "\n\nScenario errors:\n\n" + errs.map((r) => `- \`${r.scenario}\`: ${r.meta.error}`).join("\n");
        }
        parts.push(section("6. Memory across a long session", body));
    }

    // 7. load
    const bundleRec = records.find((r) => r.scenario === "bundle.static");
    const tfrRec = records.find((r) => r.scenario === "load.timeToFirstRender");
    if (bundleRec || tfrRec) {
        let body = "";
        if (bundleRec && !bundleRec.meta.error) {
            const b = bundleRec.meta;
            body += "### `library-preload.js`\n\n";
            body += table(
                ["Metric", "Value"],
                [
                    ["Raw bytes", `${kb(b.rawBytes)} KB`],
                    ["gzip", `${kb(b.gzipBytes)} KB`],
                    ["brotli", `${kb(b.brotliBytes)} KB`],
                    ["Modules bundled", String(b.moduleCount)]
                ]
            );
            body += "\n\n#### Bundle composition by category\n\n";
            const cats = Object.entries(b.byCategory).sort((a, b2) => b2[1].bytes - a[1].bytes);
            body += table(
                ["Category", "modules", "bytes", "% of bundle"],
                cats.map(([name, c]) => [
                    name,
                    String(c.count),
                    `${kb(c.bytes)} KB`,
                    ((c.bytes / b.rawBytes) * 100).toFixed(1) + "%"
                ])
            );
            body += "\n\n#### 15 largest modules in the bundle\n\n";
            body += table(
                ["Module", "bytes"],
                b.modules.slice(0, 15).map((m) => [`\`${m.name}\``, `${kb(m.bytes)} KB`])
            );
            body += "\n\n#### Other shipped artefacts\n\n";
            body += table(
                ["File", "bytes"],
                b.otherArtifacts.slice(0, 10).map((f) => [`\`${f.file}\``, `${kb(f.bytes)} KB`])
            );
        }
        const tfrRecs = records.filter((r) => /^load\.timeToFirstRender/.test(r.scenario));
        if (tfrRecs.length) {
            body += "\n\n### Time to first render, trivial 3-field schema\n\n";
            body +=
                "Cold page, HTTP cache disabled, UI5 runtime pulled from the public CDN each time. " +
                "`tCoreInit` is the UI5 framework's own bootstrap and is not MetaUI's cost; " +
                "`tMetaUIShareAfterCoreInit` is everything MetaUI adds on top of it.\n\n";
            for (const rec of tfrRecs) {
                body += `#### ${rec.label}\n\n`;
                body += table(
                    ["Phase", "median (ms)", "IQR", "min", "max", "n", "stability"],
                    Object.entries(rec.summary).map(([k, s]) => [k, ...summaryCells(s)])
                );
                body +=
                    `\n\nMetaUI resource requests: **${rec.meta.metaUiRequests}**, ` +
                    `~${kb(rec.meta.metaUiBytes)} KB, ` +
                    `\`library-preload.js\` used: **${rec.meta.usedPreload ? "yes" : "no"}**\n\n`;
            }
            const readme = tfrRecs.find((r) => r.scenario === "load.timeToFirstRender");
            if (readme) {
                body += "<details><summary>Individual MetaUI modules requested by the README integration</summary>\n\n";
                body += (readme.meta.metaUiUrls || []).map((u) => `- \`${u}\``).join("\n");
                body += "\n\n</details>\n";
            }
        }
        parts.push(section("7. Load cost", body));
    }

    parts.push("\n" + GENERATED_END + "\n");

    const generated = parts.join("\n");
    let existing = "";
    if (fs.existsSync(outPath)) {
        const prev = fs.readFileSync(outPath, "utf8");
        const endIdx = prev.indexOf(GENERATED_END);
        if (endIdx !== -1) {
            existing = prev.slice(endIdx + GENERATED_END.length);
        }
    }

    const header = "# MetaUI performance baseline\n";
    fs.writeFileSync(outPath, header + generated + existing);
}

module.exports = { writeReport, GENERATED_START, GENERATED_END };
